def old_asset_paths(snapshot):
    root = settings.static_dir.resolve()
    allowed = [root / "books", root / "book_html", root / "images" / "Book", root / "seed"]
    candidates = set()
    for row in snapshot.get("books", []):
        for field in ("file_path", "html_path", "cover_image"):
            if row.get(field):
                candidates.add(row[field])
    for row in snapshot.get("users", []):
        if row.get("avatar"):
            candidates.add(row["avatar"])
    result = []
    for value in candidates:
        if not value.startswith("/static/"):
            continue
        path = (root.parent / value.lstrip("/")).resolve()
        if path.is_relative_to(root) and any(path.is_relative_to(folder) for folder in allowed) and path.is_file():
            result.append(path)
    return result


async def export_sql():
    """Export the current demo schema/data without printing account records."""
    tables = list(Base.metadata.sorted_tables)
    output = ["-- BookApp Vietnamese demo data. Generated by reset_demo_data.py.",
              "SET NAMES utf8mb4;", "SET SESSION sql_mode='NO_AUTO_VALUE_ON_ZERO';", "SET FOREIGN_KEY_CHECKS=0;"]
    async with engine.connect() as connection:
        for table in reversed(tables):
            output.append(f"DROP TABLE IF EXISTS `{table.name}`;")
        for table in tables:
            ddl = (await connection.execute(text(f"SHOW CREATE TABLE `{table.name}`"))).first()[1]
            output.append(ddl + ";")
            rows = (await connection.execute(select(table))).mappings().all()
            if rows:
                columns = ",".join(f"`{column.name}`" for column in table.columns)
                values = ["(" + ",".join(escape_item(row[column.name], 'utf8mb4') for column in table.columns) + ")" for row in rows]
                output.append(f"INSERT INTO `{table.name}` ({columns}) VALUES\n" + ",\n".join(values) + ";")
    output.append("SET FOREIGN_KEY_CHECKS=1;")
    destination = Path(__file__).resolve().parent / "bookapp.sql"
    destination.write_text("\n\n".join(output) + "\n", encoding="utf-8")


async def reset():
    run_id = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S") + "_" + uuid4().hex[:6]
    backup_dir = Path(__file__).resolve().parent / "backups"
    backup_dir.mkdir(exist_ok=True)
    backup = backup_dir / f"before_demo_reset_{run_id}.zip"
    asset_dir = settings.static_dir / "seed" / run_id
    asset_dir.mkdir(parents=True)
    generated = []
    old_assets = []
    committed = False
    try:
        async with SessionLocal() as db:
            async with db.begin():
                tables = list(Base.metadata.sorted_tables)
                snapshot = {table.name: [dict(row) for row in (await db.execute(select(table).with_for_update())).mappings().all()] for table in tables}
                old_assets = old_asset_paths(snapshot)
                with ZipFile(backup, "w", ZIP_DEFLATED) as archive:
                    archive.writestr("tables.json", json.dumps(jsonable_encoder(snapshot), ensure_ascii=False, indent=2))
                    archive.writestr("README.txt", "Recovery copy before the demo reset. tables.json contains private account records. Do not publish this archive. Files are stored relative to backend/app/static.\n")
                    old_sql = Path(__file__).resolve().parent / "bookapp.sql"
                    if old_sql.exists():
                        archive.write(old_sql, "project/bookapp.sql")
                    for path in old_assets:
                        archive.write(path, "static/" + path.relative_to(settings.static_dir.resolve()).as_posix())
                for table in reversed(tables):
                    await db.execute(delete(table))

                users = []
                for email, password, role, name, phone in ACCOUNTS:
                    user = User(email=email, username=name, name=name, sdt=phone, role=role, password=hash_password(password), avatar="/images/Logo/Avatar.png")
                    db.add(user)
                    users.append(user)
                await db.flush()
                books, first_chapters, story_totals = [], {}, {}
                now = datetime.now(timezone.utc).replace(tzinfo=None)
                for index, item in enumerate(BOOKS + STORIES):
                    cover = asset_dir / f"cover_{index + 1}.svg"
                    cover.write_text(cover_svg(item, index), encoding="utf-8")
                    generated.append(cover)
                    book = Book(title=item["title"], author=AUTHOR, genre=item["genre"], summary=item["summary"], uploaded_by=users[0].id,
                                cover_image=f"/static/seed/{run_id}/{cover.name}", created_at=now - timedelta(days=len(BOOKS + STORIES) - index))
                    if "sections" in item:
                        blocks = [f"<h1>{escape(item['title'])}</h1>", f"<p>{AUTHOR} · Sách mẫu dành cho BookApp</p>"]
                        for title, text in item["sections"]:
                            blocks.extend([f"<h2>{escape(title)}</h2>", f"<p>{escape(text)}</p>"])
                        blocks.append("<h2>Thử thực hành</h2><p>Chọn một ý bạn muốn thử trong hôm nay. Viết lại bằng lời của mình, thêm một ví dụ gần gũi và ghi câu hỏi còn chưa rõ. Bạn có thể tô sáng đoạn văn trong reader, lưu suy nghĩ thành ghi chú hoặc dùng tính năng nghe đọc để xem lại nội dung.</p>")
                        html = asset_dir / f"book_{index + 1}.html"
                        html.write_text("\n".join(blocks), encoding="utf-8")
                        generated.append(html)
                        book.html_path = f"/static/seed/{run_id}/{html.name}"
                    db.add(book)
                    await db.flush()
                    books.append(book)
                    if "chapters" in item:
                        story_totals[book.id] = 0
                        db.add(Story(book_id=book.id, status=item["status"]))
                        await db.flush()
                        for number, (title, opening, ending) in enumerate(item["chapters"], 1):
                            content = "\n\n".join([opening, item["setting"], ending])
                            chapter = StoryChapter(book_id=book.id, number=number, title=title, content=content, page_count=max(1, len(paginate_text(content))))
                            db.add(chapter)
                            await db.flush()
                            story_totals[book.id] += chapter.page_count
                            if number == 1:
                                first_chapters[book.id] = chapter

                reader, linh = users[1], users[2]
                for index, book in enumerate(books):
                    db.add(Rating(user_id=reader.id, book_id=book.id, stars=4 if index % 3 == 0 else 5))
                    db.add(Rating(user_id=linh.id, book_id=book.id, stars=4 if index % 2 else 5))
                for book in books[:2] + books[6:8]:
                    db.add(Save(user_id=reader.id, book_id=book.id))
                for book in [books[0], books[6], books[7]]:
                    db.add(Favorite(user_id=reader.id, book_id=book.id))
                for book, text in [(books[0], "Mình thích gợi ý kể lại bằng lời của mình. Đã lưu một đoạn để thực hành."),
                                   (books[6], "Một câu chuyện nhẹ nhàng. Mục lục từng chương rất dễ theo dõi."),
                                   (books[7], "Chi tiết ánh đèn và lời hẹn cuối truyện làm mình muốn đọc lại từ đầu.")]:
                    db.add(Comment(user_id=reader.id, book_id=book.id, content=text))
                    db.add(Comment(user_id=linh.id, book_id=book.id, content="Mình đang thử nghe đọc và ghi chú. Nội dung mẫu có thể đọc ngay trong ứng dụng."))
                for book in [books[0], books[6]]:
                    if book.id in first_chapters:
                        chapter = first_chapters[book.id]
                        pages = paginate_text(chapter.content)
                        total = story_totals[book.id]
                        chapter_id = chapter.id
                    else:
                        html = next(path for path in generated if path.name == "book_1.html")
                        pages = paginate_text(html_to_text(html.read_text(encoding="utf-8")))
                        total, chapter_id = len(pages), None
                    quote = pages[0][:min(100, len(pages[0]))]
                    db.add(ReadingHistory(user_id=reader.id, book_id=book.id, last_read_at=now))
                    db.add(ReadingProgress(user_id=reader.id, book_id=book.id, page=0, total_pages=total, updated_at_ms=int(datetime.now(timezone.utc).timestamp() * 1000), chapter_id=chapter_id, chapter_page=0 if chapter_id else None, revision=1, mutation_id="demo-" + uuid4().hex))
                    db.add(Annotation(user_id=reader.id, book_id=book.id, page=0, chapter_id=chapter_id, chapter_page=0 if chapter_id else None,
                                      quote=quote, start_offset=0, end_offset=len(quote.encode("utf-16-le")) // 2, note="Ghi chú mẫu: đoạn mở đầu đáng đọc lại.", color="yellow", source_hash=page_fingerprint(pages)))
                await db.flush()
                counts = {table.name: await db.scalar(select(func.count()).select_from(table)) for table in tables}
        committed = True
        await export_sql()
        # Delete only previously referenced uploads, after the transaction commits.
        cleanup_pending = 0
        for path in old_assets:
            try:
                path.unlink(missing_ok=True)
            except OSError:
                cleanup_pending += 1
        print(json.dumps({"backup": str(backup), "counts": counts, "old_files_pending_cleanup": cleanup_pending}, ensure_ascii=False))
    except BaseException:
        # Generated assets are unique to this attempt; no existing paths are removed.
        if not committed:
            for path in generated:
                path.unlink(missing_ok=True)
        raise
    finally:
        await engine.dispose()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reset-all", action="store_true", help="Delete all existing application rows after writing a recovery archive.")
    parser.add_argument("--export-only", action="store_true", help="Refresh bookapp.sql from the current database without resetting data.")
    args = parser.parse_args()
    if args.export_only:
        async def export_only():
            try:
                await export_sql()
                print("bookapp.sql refreshed.")
            finally:
                await engine.dispose()
        asyncio.run(export_only())
    elif args.reset_all:
        asyncio.run(reset())
    else:
        parser.error("Pass --reset-all to explicitly replace existing data.")
