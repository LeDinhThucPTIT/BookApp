import asyncio
import hashlib
import logging
import os
import re
import time
import unicodedata
import uuid
from pathlib import Path

from app.config.settings import BACKEND_DIR
from app.utils.exceptions import AppError

logger = logging.getLogger(__name__)
VOICES = {"vi-VN-HoaiMyNeural": "Hoài My · Nữ", "vi-VN-NamMinhNeural": "Nam Minh · Nam"}


def split_tts_text(text: str, limit: int = 300) -> list[str]:
    text = " ".join(text.split())
    chunks = []
    while len(text) > limit:
        boundaries = list(re.finditer(r'[.!?…;:][”"’»)]*\s+', text[:limit + 1]))
        cut = boundaries[-1].end() if boundaries and boundaries[-1].end() >= limit // 3 else text.rfind(" ", 0, limit + 1)
        if cut <= 0:
            cut = limit
        chunks.append(text[:cut].strip())
        text = text[cut:].lstrip()
    if text:
        chunks.append(text)
    return chunks


class TTSService:
    """Bounded page synthesis with shared in-flight work and a private disk cache."""

    def __init__(self, cache_dir: Path | None = None):
        self.cache_dir = cache_dir or BACKEND_DIR / ".cache" / "tts"
        self.pending = {}
        self.slots = asyncio.Semaphore(2)
        self.ttl = 7 * 24 * 3600
        self.max_cache_bytes = 256 * 1024 * 1024

    def _read_cache(self, path):
        try:
            if time.time() - path.stat().st_mtime > self.ttl:
                return None
            audio = path.read_bytes()
            if audio:
                path.touch()
                return audio
        except OSError:
            pass
        return None

    def _save_cache(self, path, audio):
        self.cache_dir.mkdir(parents=True, exist_ok=True)
        temporary = path.with_suffix(f".{uuid.uuid4().hex}.tmp")
        try:
            temporary.write_bytes(audio)
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)
        # Only files generated by this service are eligible for cache eviction.
        entries = []
        for candidate in self.cache_dir.glob("*.mp3"):
            try:
                stat = candidate.stat()
                entries.append((stat.st_mtime, stat.st_size, candidate))
            except OSError:
                continue
        total = sum(size for _, size, _ in entries)
        for modified, size, candidate in sorted(entries):
            if candidate == path:
                continue
            if time.time() - modified > self.ttl or total > self.max_cache_bytes:
                try:
                    candidate.unlink(missing_ok=True)
                    total -= size
                except OSError:
                    pass

    async def _render(self, text, voice):
        import edge_tts

        data = bytearray()
        # Keep requests below the service's UTF-8 splitting threshold and favor
        # sentence boundaries. MP3 frame streams can be concatenated directly.
        for part in split_tts_text(text):
            communicate = edge_tts.Communicate(part, voice, connect_timeout=10, receive_timeout=20)
            received = False
            async for chunk in communicate.stream():
                if chunk["type"] == "audio":
                    received = True
                    data.extend(chunk["data"])
                    if len(data) > 5 * 1024 * 1024:
                        raise RuntimeError("TTS audio exceeded page limit")
            if not received:
                raise RuntimeError("TTS returned an empty segment")
        if not data:
            raise RuntimeError("TTS returned no audio")
        return bytes(data)

    async def _generate(self, text, voice, path):
        try:
            async with asyncio.timeout(50):
                async with self.slots:
                    audio = await self._render(text, voice)
            try:
                await asyncio.to_thread(self._save_cache, path, audio)
            except OSError:
                logger.warning("Unable to write TTS cache")
            return audio
        except Exception as exc:
            logger.warning("Edge TTS failed: %s", type(exc).__name__)
            raise AppError("Dịch vụ giọng đọc chưa phản hồi. Vui lòng thử lại sau.", 503, "TTS_UNAVAILABLE") from exc

    async def audio(self, text: str, voice: str) -> bytes:
        if voice not in VOICES:
            raise AppError("Giọng đọc không được hỗ trợ.", 422, "INVALID_VOICE")
        text = unicodedata.normalize("NFC", text).strip()
        if not text or len(text) > 4000:
            raise AppError("Trang này chưa có văn bản phù hợp để nghe đọc.", 422, "INVALID_TTS_TEXT")
        key = hashlib.sha256(f"edge-v2\0{voice}\0{text}".encode("utf-8")).hexdigest()
        path = self.cache_dir / f"{key}.mp3"
        cached = await asyncio.to_thread(self._read_cache, path)
        if cached:
            return cached
        task = self.pending.get(key)
        if task is None:
            if len(self.pending) >= 8:
                raise AppError("Giọng đọc đang bận. Vui lòng thử lại sau ít giây.", 503, "TTS_BUSY")
            task = asyncio.create_task(self._generate(text, voice, path))
            self.pending[key] = task
            def finished(result):
                self.pending.pop(key, None)
                if not result.cancelled():
                    result.exception()  # Consume failures even if the requesting client disconnected.
            task.add_done_callback(finished)
        return await asyncio.shield(task)


tts_service = TTSService()
